const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const h5 = path.join(root, 'h5');
const pagesDir = path.join(h5, 'pages');
const output = path.join(h5, 'page-templates.js');
const pageOrder = ['home', 'talent', 'recruit', 'roster', 'shop', 'duel', 'result', 'profile', 'pointshop'];

const templates = {};
for (const page of pageOrder) {
  const file = path.join(pagesDir, `${page}.html`);
  const source = fs.readFileSync(file, 'utf8').trim();
  if (!new RegExp(`^<main id="${page}" class="screen(?: active)?"`).test(source)) {
    throw new Error(`${file} must contain the expected root <main>`);
  }
  if (/<\/?(?:script|iframe|object|embed|base|form)\b/i.test(source) || /\son[a-z]+\s*=/i.test(source)) {
    throw new Error(`${file} contains executable or forbidden markup`);
  }
  for (const match of source.matchAll(/\bsrc="([^"]+)"/g)) {
    const value = match[1];
    if (!value.startsWith('../assets/')) throw new Error(`${file} contains unsupported resource path: ${value}`);
    const asset = path.resolve(pagesDir, value);
    if (!asset.startsWith(`${h5}${path.sep}`) || !fs.existsSync(asset)) {
      throw new Error(`${file} references a missing resource: ${value}`);
    }
  }
  templates[page] = source.replaceAll('src="../assets/', 'src="assets/');
}

const banner = '// Generated by scripts/build-page-templates.cjs. Do not edit directly.\n';
fs.writeFileSync(output, `${banner}window.SupFusionPageTemplates = Object.freeze(${JSON.stringify(templates, null, 2)});\n`);
console.log(`Built ${pageOrder.length} page templates.`);
